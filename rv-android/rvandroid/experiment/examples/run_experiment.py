# rvandroid/experiment/examples/run_experiment.py
"""
Example script for running experiments with the unified execution framework.

This script demonstrates how to create and execute experiments using the
new unified execution framework. It configures and runs a standard experiment
workflow, including preparation, static analysis, execution, analysis, and
reporting phases.
"""

import os
import sys
import argparse
from typing import List

from rvandroid.app import App
from rvandroid.experiment.core.conductor import ExperimentConductor
from rvandroid.experiment.processor import (
    PreparationProcessor,
    StaticAnalysisProcessor,
    ExecutionProcessor,
    AnalysisProcessor,
    ReportingProcessor
)
from rvandroid.tools.registry import ToolRegistry
from settings import RESULTS_DIR, INSTRUMENTED_DIR


def parse_arguments():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description="Run experiment with the unified execution framework")
    
    parser.add_argument(
        "--repetitions", type=int, default=1,
        help="Number of repetitions for each task (default: 1)"
    )
    parser.add_argument(
        "--timeouts", type=int, nargs="+", default=[60],
        help="Timeout values in seconds (default: 60)"
    )
    parser.add_argument(
        "--tools", type=str, nargs="+", default=["monkey"],
        help="Tools to use for testing (default: monkey)"
    )
    parser.add_argument(
        "--apks", type=str, nargs="+", default=None,
        help="APKs to test (default: all instrumented APKs)"
    )
    parser.add_argument(
        "--generate-monitors", action="store_true", default=False,
        help="Generate runtime verification monitors"
    )
    parser.add_argument(
        "--instrument", action="store_true", default=False,
        help="Instrument APKs with runtime verification monitors"
    )
    parser.add_argument(
        "--static-analysis", action="store_true", default=False,
        help="Perform static analysis on APKs"
    )
    parser.add_argument(
        "--skip-execution", action="store_true", default=False,
        help="Skip task execution phase"
    )
    parser.add_argument(
        "--no-window", action="store_true", default=False,
        help="Run emulator without a window"
    )
    parser.add_argument(
        "--results-dir", type=str, default=None,
        help="Directory for storing results (default: autogenerated)"
    )
    
    return parser.parse_args()


def get_apps(apks: List[str]) -> List[App]:
    """
    Get App objects for the specified APKs.
    
    Args:
        apks: List of APK names or paths
        
    Returns:
        List of App objects
    """
    apps = []
    
    # If APKs are specified by name, look for them in the instrumented directory
    for apk in apks:
        if os.path.exists(apk):
            # APK is a direct path
            apps.append(App(apk))
        else:
            # Look for APK in instrumented directory
            apk_path = os.path.join(INSTRUMENTED_DIR, apk)
            if os.path.exists(apk_path):
                apps.append(App(apk_path))
            else:
                print(f"Warning: APK not found: {apk}")
                
    return apps


def get_tools(tool_names: List[str]) -> List:
    """
    Get tool objects for the specified tool names.
    
    Args:
        tool_names: List of tool names
        
    Returns:
        List of tool objects
    """
    registry = ToolRegistry.get_instance()
    tools = []
    
    for name in tool_names:
        tool = registry.get_tool(name)
        if tool:
            tools.append(tool)
        else:
            print(f"Warning: Tool not found: {name}")
            
    return tools


def main():
    """Main entry point for the script."""
    # Parse arguments
    args = parse_arguments()
    
    # Set up tools
    tools = get_tools(args.tools)
    
    if not tools:
        print("Error: No valid tools specified")
        sys.exit(1)
        
    # Set up APKs
    if args.apks:
        apps = get_apps(args.apks)
        
        if not apps:
            print("Error: No valid APKs specified")
            sys.exit(1)
    else:
        apps = []  # Will be loaded during preparation phase
        
    # Create experiment conductor
    results_dir = args.results_dir or RESULTS_DIR
    conductor = ExperimentConductor(
        results_dir=results_dir,
        processor_classes=[
            PreparationProcessor,
            StaticAnalysisProcessor,
            ExecutionProcessor,
            AnalysisProcessor,
            ReportingProcessor
        ]
    )
    
    # Run experiment
    success = conductor.execute_standard_experiment(
        apks=apps,
        tools=tools,
        repetitions=args.repetitions,
        timeouts=args.timeouts,
        generate_monitors=args.generate_monitors,
        instrument=args.instrument,
        static_analysis=args.static_analysis,
        skip_execution=args.skip_execution,
        no_window=args.no_window
    )
    
    # Report result
    if success:
        print(f"Experiment completed successfully: {conductor.experiment_id}")
        print(f"Results available at: {conductor.results_dir}")
        sys.exit(0)
    else:
        print(f"Experiment failed: {conductor.experiment_id}")
        print(f"Results available at: {conductor.results_dir}")
        sys.exit(1)


if __name__ == "__main__":
    main()