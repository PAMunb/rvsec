"""
Static analysis data model for comprehensive Android application analysis.

This module provides structured data models for representing the complete
static analysis results from multiple analysis tools.
"""

from typing import Optional

from pydantic import ConfigDict, Field

# Direct imports - static.py should be imported after other domain modules
from rv_android_core.domain.classes import Classes
from rv_android_core.domain.components import Components
from rv_android_core.domain.window import Windows
from rv_android_core.domain.wtg import WindowTransitionGraph
from rv_android_core.util.validation import BaseValidatedModel
from rv_android_core.util.validation.decorators import validated_model


@validated_model(["classes", "windows", "wtg"])
class StaticAnalysisData(BaseValidatedModel):
    """
    Comprehensive data model for static analysis results from Android applications.

    This model aggregates analysis results from multiple static analysis tools
    (GESDA, GATOR, REACH) into a unified representation that supports both
    validation and serialization for downstream processing components.

    ### Architectural Role:
    - Serves as the primary data contract for static analysis output
    - Provides structured access to application structure, UI, and reachability data
    - Enables consistent data flow between analysis and experiment components
    - Supports validation of analysis completeness and data integrity

    ### Integration Points:
    - Generated by StaticAnalysisParser from raw tool outputs
    - Consumed by coverage analyzers for static-dynamic correlation
    - Used by experiment systems for comprehensive application understanding
    - Integrated with result storage and reporting pipelines

    ### Configuration:
    Inherits arbitrary_types_allowed=True from BaseValidatedModel for complex types.
    Enables validation of nested BaseValidatedModel instances.
    """

    model_config = ConfigDict(
        # Enable validation of nested Pydantic models
        arbitrary_types_allowed=True,
        # Accept existing BaseValidatedModel instances
        validate_default=True,
    )

    classes: Classes = Field(
        description="Application class structure and component information from GESDA analysis"
    )
    windows: Windows = Field(
        description="UI window and layout information extracted from static analysis"
    )
    wtg: WindowTransitionGraph = Field(
        description="Window transition graph representing application navigation flows from GATOR analysis"
    )
    components: Components = Field(
        default_factory=Components,
        description="Component data (Activities, Services, Receivers, Providers) with intent-filters, authorities, and MOP reachability",
    )
    code_package: Optional[str] = Field(
        default=None,
        description=(
            "The scope key the GATOR run actually filtered by, as the producer "
            "recorded it (INV-ANA-66). None for the 162 artefacts written before "
            "the key reached disk, and for any artefact whose producer passed no "
            "codePackage — the `package` member is the MANIFEST package whatever "
            "key was used, so it cannot stand in for this one (INV-ANA-58)."
        ),
    )
    code_package_source: Optional[str] = Field(
        default=None,
        description=(
            'Origin of `code_package`: "manifest", "manifest-neutralized" or '
            '"detector". None when the artefact does not record one.'
        ),
    )
    class_defs_under_key: Optional[int] = Field(
        default=None,
        description=(
            "Compiled classes under `code_package` that survive the client's own "
            "isAppClass filter — the NET count the denominator gate divides by "
            "(INV-ANA-66, INV-ANA-69). None when the artefact does not record one; "
            "the producer writes -1 in that case and the parser maps it to None, so "
            "'not recorded' stays distinguishable from a genuine zero universe."
        ),
    )
    complete: bool = Field(
        default=False,
        description=(
            "ADR-6 sentinel — True when the GATOR producer emitted "
            '"complete":true as the last top-level JSON field (signaling '
            "all sections finished writing) and the parser observed it. "
            "False when the file is from a pre-sentinel run, a partial "
            "(WTG-timeout) write, or a writer crash. Consumers requiring "
            "completeness (G_widget_reachability, sweep gates) MUST filter "
            "on this flag."
        ),
    )
