package presto.android.gui.clients.target;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

/**
 * Covers the per-line parsing contract for {@link SignatureFileTargetSource}:
 * blank lines, comments, STRICT entries, wildcard LENIENT entries, and the
 * INV-ANA-34 invariant that malformed lines surface {@link IllegalArgumentException}
 * with the offending 1-based line number.
 */
public class SignatureFileTargetSourceTest {

	@Rule
	public TemporaryFolder tmp = new TemporaryFolder();

	private Path write(String body) throws IOException {
		Path p = tmp.newFile("targets.txt").toPath();
		Files.write(p, body.getBytes(StandardCharsets.UTF_8));
		return p;
	}

	@Test
	public void blankLinesAndCommentsAreIgnored() throws Exception {
		Path p = write(""
				+ "# JCA targets, generated by foo.py\n"
				+ "\n"
				+ "   \n"
				+ "  # leading-whitespace comment\n"
				+ "<javax.crypto.Cipher: void init(int,java.security.Key)>\n");
		var out = new SignatureFileTargetSource(p).load();
		assertEquals(1, out.size());
	}

	@Test
	public void strictEntryParsesAllFields() throws Exception {
		Path p = write("<javax.crypto.Cipher: void init(int,java.security.Key)>\n");
		var out = new SignatureFileTargetSource(p).load();
		assertEquals(1, out.size());
		TargetMethod t = out.iterator().next();
		assertEquals("javax.crypto.Cipher", t.getClassName());
		assertEquals("init", t.getMethodName());
		assertEquals(2, t.getParams().size());
		assertEquals("int", t.getParams().get(0));
		assertEquals("java.security.Key", t.getParams().get(1));
		assertEquals(TargetMethod.MatchPolicy.STRICT, t.getPolicy());
		assertNotNull(t.getSignature());
	}

	@Test
	public void wildcardDotsYieldsLenientEntry() throws Exception {
		Path p = write("<javax.crypto.Cipher: void init(..)>\n");
		var out = new SignatureFileTargetSource(p).load();
		assertEquals(1, out.size());
		TargetMethod t = out.iterator().next();
		assertEquals("javax.crypto.Cipher", t.getClassName());
		assertEquals("init", t.getMethodName());
		assertTrue(t.getParams().isEmpty());
		assertEquals(TargetMethod.MatchPolicy.LENIENT, t.getPolicy());
	}

	@Test
	public void wildcardStarYieldsLenientEntry() throws Exception {
		Path p = write("<java.security.MessageDigest: byte[] digest(*)>\n");
		var out = new SignatureFileTargetSource(p).load();
		TargetMethod t = out.iterator().next();
		assertEquals(TargetMethod.MatchPolicy.LENIENT, t.getPolicy());
	}

	@Test
	public void mixedStrictAndLenientCoexist() throws Exception {
		Path p = write(""
				+ "<javax.crypto.Cipher: void init(int,java.security.Key)>\n"
				+ "<javax.crypto.Cipher: byte[] doFinal(..)>\n");
		var out = new SignatureFileTargetSource(p).load();
		assertEquals(2, out.size());
		long strict = out.stream().filter(t -> t.getPolicy() == TargetMethod.MatchPolicy.STRICT).count();
		long lenient = out.stream().filter(t -> t.getPolicy() == TargetMethod.MatchPolicy.LENIENT).count();
		assertEquals(1, strict);
		assertEquals(1, lenient);
	}

	@Test
	public void zeroArgStrictEntry() throws Exception {
		Path p = write("<X: void f()>\n");
		var out = new SignatureFileTargetSource(p).load();
		TargetMethod t = out.iterator().next();
		assertEquals(TargetMethod.MatchPolicy.STRICT, t.getPolicy());
		assertTrue(t.getParams().isEmpty());
	}

	@Test
	public void malformedLineRaisesWithFileAndLineNumber() throws Exception {
		Path p = write(""
				+ "# valid above\n"
				+ "<javax.crypto.Cipher: void init(int,java.security.Key)>\n"
				+ "garbage line without brackets\n");
		try {
			new SignatureFileTargetSource(p).load();
			fail("Expected IllegalArgumentException on line 3");
		} catch (IllegalArgumentException e) {
			String msg = e.getMessage();
			assertTrue("Error must reference offending line number 3 — got: " + msg,
					msg.contains(":3"));
			assertTrue("Error must reference file path — got: " + msg,
					msg.contains(p.toString()));
			assertTrue("Error must echo the malformed content — got: " + msg,
					msg.contains("garbage line without brackets"));
		}
	}

	@Test
	public void missingFileRaisesIllegalState() {
		Path absent = tmp.getRoot().toPath().resolve("does-not-exist.txt");
		try {
			new SignatureFileTargetSource(absent).load();
			fail("Expected IllegalStateException for missing file");
		} catch (IllegalStateException expected) {
			assertTrue(expected.getMessage().contains(absent.toString()));
		}
	}

	@Test
	public void emptyFileYieldsEmptySet() throws Exception {
		Path p = write("");
		assertEquals(0, new SignatureFileTargetSource(p).load().size());
	}
}
